def _action_params(rule_id: str, action: RuleAction, desc: str) -> dict:
    base = {"catalog": "remark_ext_100", "rule_id": rule_id}
    if action == RuleAction.TAG_HIGH_RISK:
        base["risk_level"] = "high"
    base["reason"] = rule_id
    base["summary"] = desc[:120]
    return base


def build_ext_remark_100_rules() -> List[RiskRuleIR]:
    out: List[RiskRuleIR] = []
    for i, desc in enumerate(_EXT_DESCRIPTIONS, start=1):
        rid = f"ext_r{i:03d}"
        field = f"m{i:03d}"
        act = _classify_action(desc)
        out.append(
            RiskRuleIR(
                rule_id=rid,
                description_cn=desc[:512],
                conditions=[
                    RuleCondition(
                        entity="ext",
                        field=field,
                        op=">=",
                        value=10**12,
                        time_window=None,
                    )
                ],
                action=act,
                action_params=_action_params(rid, act, desc),
                enabled=True,
                priority=400 + i,
            )
        )
    return out


EXT_REMARK_100_RULES: List[RiskRuleIR] = build_ext_remark_100_rules()
